-- PostgreSQL port of the gRAS (gPAS web-UI auth) schema.
--
-- MySQL used a separate `gras` database; here it is a schema inside the
-- single "gpas" Postgres database (grasDS connects with
-- ?currentSchema=gras, see services/gpas/jboss_pg/configure_wildfly_gras.cli),
-- authenticating as the same role as everything else (gpas_user, per
-- TTP_DB_USER in docker-compose.yml) - there is no separate gras_user role.
--
-- This schema backs the elytron JdbcRealm (TtpRealm) that gpas-web's login
-- form authenticates against, querying the domainuser_password /
-- domainuser_role views defined below. Without this file, nobody can log
-- into the gPAS web UI at all.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS gras;
-- "public" stays on the path so pgcrypto's digest() (installed there) remains visible.
SET search_path TO gras, public;

CREATE TABLE IF NOT EXISTS domain (
    name VARCHAR(255) NOT NULL DEFAULT '',
    description VARCHAR(255) NOT NULL DEFAULT '',
    PRIMARY KEY (name)
);

CREATE TABLE IF NOT EXISTS project (
    name VARCHAR(255) NOT NULL DEFAULT '',
    description VARCHAR(255) NOT NULL DEFAULT '',
    PRIMARY KEY (name)
);

CREATE TABLE IF NOT EXISTS group_ (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL DEFAULT '',
    project_name VARCHAR(255) NOT NULL DEFAULT '',
    description VARCHAR(255) NOT NULL DEFAULT '',
    PRIMARY KEY (id),
    CONSTRAINT unique_name_project UNIQUE (name, project_name),
    CONSTRAINT fk_project_group FOREIGN KEY (project_name) REFERENCES project (name)
);

CREATE TABLE IF NOT EXISTS role (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL DEFAULT '',
    project_name VARCHAR(255) NOT NULL DEFAULT '',
    description VARCHAR(255) NOT NULL DEFAULT '',
    PRIMARY KEY (id),
    CONSTRAINT unique_role_name UNIQUE (name),
    CONSTRAINT fk_project_role FOREIGN KEY (project_name) REFERENCES project (name)
);

CREATE TABLE IF NOT EXISTS group_role_mapping (
    group_id INT NOT NULL,
    role_id INT NOT NULL,
    PRIMARY KEY (group_id, role_id),
    CONSTRAINT fk_group FOREIGN KEY (group_id) REFERENCES group_ (id) ON DELETE CASCADE,
    CONSTRAINT fk_role FOREIGN KEY (role_id) REFERENCES role (id)
);

CREATE TABLE IF NOT EXISTS "user" (
    name VARCHAR(255) NOT NULL DEFAULT '',
    password VARCHAR(255),
    active SMALLINT DEFAULT 1,
    description VARCHAR(255) NOT NULL DEFAULT '',
    email VARCHAR(255) NOT NULL DEFAULT '',
    PRIMARY KEY (name)
);

CREATE TABLE IF NOT EXISTS permission (
    group_id INT NOT NULL,
    user_name VARCHAR(255) NOT NULL DEFAULT '',
    domain_name VARCHAR(255) NOT NULL DEFAULT '',
    PRIMARY KEY (group_id, user_name, domain_name),
    CONSTRAINT fk_permission_domain FOREIGN KEY (domain_name) REFERENCES domain (name),
    CONSTRAINT fk_permission_group FOREIGN KEY (group_id) REFERENCES group_ (id),
    CONSTRAINT fk_permission_user FOREIGN KEY (user_name) REFERENCES "user" (name)
);

CREATE TABLE IF NOT EXISTS hist_domain (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
    "timestamp" TIMESTAMP NOT NULL,
    action VARCHAR(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS hist_group_ (
