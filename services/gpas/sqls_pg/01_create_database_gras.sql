-- *** comfort procedures (called from 02_init_database_gras_for_gpas.sql) ***

CREATE OR REPLACE PROCEDURE createDomain(IN domainName VARCHAR(255), IN description VARCHAR(255))
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO domain (name, description) VALUES (domainName, description)
        ON CONFLICT (name) DO NOTHING;
END;
$$;

CREATE OR REPLACE PROCEDURE createProject(IN projectName VARCHAR(255), IN description VARCHAR(255))
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO project (name, description) VALUES (projectName, description)
        ON CONFLICT (name) DO NOTHING;
END;
$$;

CREATE OR REPLACE PROCEDURE disableUser(IN userName VARCHAR(255))
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE "user" SET active = 0 WHERE name = userName;
END;
$$;

CREATE OR REPLACE PROCEDURE enableUser(IN userName VARCHAR(255))
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE "user" SET active = 1 WHERE name = userName;
END;
$$;

CREATE OR REPLACE PROCEDURE changePassword(IN userName VARCHAR(255), IN newPassword VARCHAR(255))
LANGUAGE plpgsql
SET search_path = gras, public
AS $$
BEGIN
    UPDATE "user" SET password = encode(digest(newPassword::bytea, 'sha256'), 'hex') WHERE name = userName;
END;
$$;

CREATE OR REPLACE PROCEDURE createUser(IN userName VARCHAR(255), IN password VARCHAR(255), IN description VARCHAR(255))
LANGUAGE plpgsql
SET search_path = gras, public
AS $$
BEGIN
    INSERT INTO "user" (name, password, active, description)
        VALUES (userName, encode(digest(password::bytea, 'sha256'), 'hex'), 1, description)
        ON CONFLICT (name) DO NOTHING;
END;
$$;

CREATE OR REPLACE PROCEDURE createGroup(IN projectName VARCHAR(255), IN groupName VARCHAR(255), IN description VARCHAR(255))
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO group_ (name, project_name, description) VALUES (groupName, projectName, description)
        ON CONFLICT (name, project_name) DO NOTHING;
END;
$$;

CREATE OR REPLACE PROCEDURE createRole(IN projectName VARCHAR(255), IN roleName VARCHAR(255), IN description VARCHAR(255))
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO role (name, project_name, description) VALUES (roleName, projectName, description)
        ON CONFLICT (name) DO NOTHING;
END;
$$;

CREATE OR REPLACE PROCEDURE createGroupRoleMapping(IN projectName VARCHAR(255), IN groupName VARCHAR(255), IN roleName VARCHAR(255))
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO group_role_mapping (group_id, role_id) VALUES (
        (SELECT id FROM group_ WHERE name = groupName AND project_name = projectName),
        (SELECT id FROM role WHERE name = roleName)
    ) ON CONFLICT (group_id, role_id) DO NOTHING;
END;
$$;

CREATE OR REPLACE PROCEDURE grantAdminRights(IN domainName VARCHAR(255), IN projectName VARCHAR(255), IN userName VARCHAR(255))
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO permission (group_id, user_name, domain_name)
        SELECT DISTINCT id, userName, domainName FROM group_ WHERE project_name = projectName
        ON CONFLICT (group_id, user_name, domain_name) DO NOTHING;
END;
$$;

CREATE OR REPLACE PROCEDURE grantStandardRights(IN domainName VARCHAR(255), IN projectName VARCHAR(255), IN userName VARCHAR(255))
LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM permission p USING group_ g
        WHERE p.group_id = g.id AND p.user_name = userName AND p.domain_name = domainName AND g.project_name = projectName;
    INSERT INTO permission (group_id, user_name, domain_name)
        SELECT DISTINCT id, userName, domainName FROM group_
        WHERE project_name = projectName AND name !~ '[aA]dmin';
END;
$$;

-- Manual credential-check helper (not called by the deployed app - the
-- elytron JdbcRealm queries the views above directly). Kept as a function
-- since Postgres procedures cannot return a result set the way MySQL's could.
CREATE OR REPLACE FUNCTION testCredetials(userName VARCHAR(255), passwd VARCHAR(255))
RETURNS TABLE (roles VARCHAR)
LANGUAGE sql
SET search_path = gras, public
AS $$
    SELECT DISTINCT r.name AS roles
    FROM permission p
        JOIN group_role_mapping m ON p.group_id = m.group_id
        JOIN role r ON m.role_id = r.id
        JOIN "user" u ON u.name = p.user_name AND u.active = 1
    WHERE CONCAT_WS('@', p.user_name, p.domain_name) = userName
        AND u.password = encode(digest(passwd::bytea, 'sha256'::text), 'hex');
$$;

