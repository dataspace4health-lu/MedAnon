CREATE TABLE IF NOT EXISTS hist_user (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL DEFAULT '',
    password VARCHAR(255),
    active SMALLINT DEFAULT 1,
    description VARCHAR(255) NOT NULL DEFAULT '',
    email VARCHAR(255) NOT NULL DEFAULT '',
    "timestamp" TIMESTAMP NOT NULL,
    action VARCHAR(255) NOT NULL,
    PRIMARY KEY (id)
);

-- Views backing the elytron JdbcRealm (TtpRealm) login query - see
-- services/gpas/jboss_pg/configure_wildfly_gras.cli's principal-query.
CREATE OR REPLACE VIEW domainuser_password AS
    SELECT DISTINCT CONCAT_WS('@', p.user_name, p.domain_name) AS domainuser, u.password AS password
    FROM permission p JOIN "user" u ON u.name = p.user_name
    WHERE u.active = 1;

CREATE OR REPLACE VIEW domainuser_role AS
    SELECT DISTINCT CONCAT_WS('@', p.user_name, p.domain_name) AS domainuser, r.name AS role
    FROM permission p
        JOIN group_role_mapping m ON p.group_id = m.group_id
        JOIN role r ON m.role_id = r.id
        JOIN "user" u ON u.name = p.user_name
    WHERE u.active = 1;

CREATE OR REPLACE VIEW validate AS
    SELECT DISTINCT a.domainuser AS domainuser, a.password AS password, b.role AS role
    FROM domainuser_password a JOIN domainuser_role b ON a.domainuser = b.domainuser;

-- *** audit-history + referential-cleanup triggers ***
-- BEFORE DELETE/UPDATE triggers that both log to the hist_* tables and
-- (for delete) cascade-clean dependent rows, mirroring the MySQL originals.

CREATE OR REPLACE FUNCTION gras_delete_domain() RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO hist_domain (name, description, "timestamp", action)
        VALUES (OLD.name, OLD.description, now(), 'delete');
    DELETE FROM permission WHERE domain_name = OLD.name;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS delete_domain ON domain;
CREATE TRIGGER delete_domain BEFORE DELETE ON domain
    FOR EACH ROW EXECUTE FUNCTION gras_delete_domain();

CREATE OR REPLACE FUNCTION gras_delete_group() RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO hist_group_ (group_id, name, project_name, description, "timestamp", action)
        VALUES (OLD.id, OLD.name, OLD.project_name, OLD.description, now(), 'delete');
    DELETE FROM group_role_mapping WHERE group_id = OLD.id;
    DELETE FROM permission WHERE group_id = OLD.id;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS delete_group ON group_;
CREATE TRIGGER delete_group BEFORE DELETE ON group_
    FOR EACH ROW EXECUTE FUNCTION gras_delete_group();

CREATE OR REPLACE FUNCTION gras_delete_group_role_mapping() RETURNS TRIGGER AS $$
