CREATE TABLE IF NOT EXISTS hist_role (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    role_id INT NOT NULL,
    name VARCHAR(255) NOT NULL,
    project_name VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
