CREATE OR REPLACE FUNCTION gras_insert_group_role_mapping() RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM role r, group_ g
        WHERE r.id = NEW.role_id AND g.id = NEW.group_id AND g.project_name = r.project_name
    ) THEN
        RAISE EXCEPTION 'Role and Group have to belong to the same Project';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS insert_group_role_mapping ON group_role_mapping;
CREATE TRIGGER insert_group_role_mapping BEFORE INSERT ON group_role_mapping
    FOR EACH ROW EXECUTE FUNCTION gras_insert_group_role_mapping();

